-- Assembles the in-game mod into the single Lua file Chef Shared Loader runs. (Lua 5.1)
--
--   lua5.1 build/assemble.lua [enemy_hp_lua] [output]
--
-- The output starts with the HD2-Addon header, then bundles data/enemies.lua, data/spawn_tables.lua,
-- data/game_names.lua, src/roster.lua and the hash -> name table behind a local `require`, then the mod
-- body (mod/enemy_intel.lua). Nothing is written to _G: the shim and the bundle are locals.
--
-- The hash -> name table is read from your local copy of the Enemy HP mod at build time instead of
-- being kept in this repository. Ask its author before publishing a build that bundles it.

local ADDON_NAME = "mods/vixenhunny/enemy_intel"
local DEFAULT_EHP = "C:/Users/Admin/Documents/HellForge/mods/Enemy HP 1.1.1 (with names) 16650 1.1.1 "
  .. "2026-09-27T21-16Z uF6f3KilO_AR764431/Addon/0cdb2ce39c96e9a4.lua"

local root = ((arg and arg[0] or ""):match("^(.*[/\\])build[/\\]") or "./")
package.path = root .. "?.lua;" .. package.path

local ehp_path = arg[1] or DEFAULT_EHP
local out_path = arg[2] or (root .. "dist/enemy_intel.lua")

local function read(path)
  local handle, err = io.open(path, "rb")
  if not handle then
    error("cannot read " .. path .. ": " .. tostring(err), 0)
  end
  local body = handle:read("*a")
  handle:close()
  if body:sub(1, 3) == "\239\187\191" then
    error(path .. " starts with a UTF-8 BOM; the loader rejects that", 0)
  end
  return body
end

-- Hash -> name pairs from the Enemy HP source: lines like  ["FB9937035D652C43"] = "Trooper",
local function extract_names(source)
  local names, count = {}, 0
  for hash, name in source:gmatch('%[%s*"(%x+)"%s*%]%s*=%s*"([^"\n]*)"') do
    if #hash == 16 then
      names[hash:lower()] = name
      count = count + 1
    end
  end
  return names, count
end

local hash_names, hash_count = extract_names(read(ehp_path))
if hash_count == 0 then
  error("no hash -> name entries found in " .. ehp_path, 0)
end

-- Check every game name and enemy id before building, so a typo fails here instead of silently
-- never matching in game.
local Enemies = require("data.enemies")
local GameNames = require("data.game_names")
local known_names, known_ids, problems = {}, {}, {}
for _, name in pairs(hash_names) do known_names[name] = true end
for _, def in ipairs(Enemies) do known_ids[def.id] = true end
for game_name, spec in pairs(GameNames) do
  if not known_names[game_name] then
    problems[#problems + 1] = "data/game_names.lua: '" .. game_name .. "' is not a name in the hash table"
  end
  local id = type(spec) == "string" and spec or spec.id
  if id and not known_ids[id] then
    problems[#problems + 1] = "data/game_names.lua: '" .. game_name .. "' points at unknown enemy id '" .. id .. "'"
  end
  if type(spec) == "table" and not id and not (spec.name and spec.faction and spec.class) then
    problems[#problems + 1] = "data/game_names.lua: '" .. game_name .. "' needs id, or name + faction + class"
  end
end
if #problems > 0 then
  table.sort(problems)
  error("assemble failed:\n  " .. table.concat(problems, "\n  "), 0)
end

local hashes = {}
for hash in pairs(hash_names) do hashes[#hashes + 1] = hash end
table.sort(hashes)
local name_lines = {}
for _, hash in ipairs(hashes) do
  name_lines[#name_lines + 1] = string.format("  [%q] = %q,", hash, hash_names[hash])
end

local MODULES = {
  { "data.enemies", "data/enemies.lua" },
  { "data.spawn_tables", "data/spawn_tables.lua" },
  { "data.game_names", "data/game_names.lua" },
  { "src.roster", "src/roster.lua" },
}

local parts = {
  "-- HD2-Addon: " .. ADDON_NAME,
  "-- Enemy Intel. GENERATED by build/assemble.lua from the EnemyData sources; edit those and rebuild.",
  "",
  "local BUNDLE, LOADED = {}, {}",
  "local function require(name)",
  "  if LOADED[name] == nil then",
  "    local load_module = BUNDLE[name]",
  "    if load_module == nil then",
  "      error(\"enemy_intel: module '\" .. tostring(name) .. \"' is not bundled\", 2)",
  "    end",
  "    LOADED[name] = load_module()",
  "  end",
  "  return LOADED[name]",
  "end",
  "",
}
for _, module in ipairs(MODULES) do
  parts[#parts + 1] = string.format("BUNDLE[%q] = function()", module[1])
  parts[#parts + 1] = (read(root .. module[2]):gsub("%s+$", ""))
  parts[#parts + 1] = "end"
  parts[#parts + 1] = ""
end
parts[#parts + 1] = 'BUNDLE["generated.hash_names"] = function()'
parts[#parts + 1] = "return {"
parts[#parts + 1] = table.concat(name_lines, "\n")
parts[#parts + 1] = "}"
parts[#parts + 1] = "end"
parts[#parts + 1] = ""
parts[#parts + 1] = (read(root .. "mod/enemy_intel.lua"):gsub("%s+$", ""))
parts[#parts + 1] = ""

local source = table.concat(parts, "\n")
local compiled, compile_error = loadstring(source, "@" .. out_path)
if not compiled then
  error("assembled mod does not compile: " .. tostring(compile_error), 0)
end

local handle = assert(io.open(out_path, "wb"))
handle:write(source)
handle:close()
print(string.format("wrote %s (%d bytes): %d hashes from %s, %d game names checked",
  out_path, #source, hash_count, ehp_path, (function() local n = 0 for _ in pairs(GameNames) do n = n + 1 end return n end)()))
